function openFormModal(config){

    const overlay=
        document.getElementById(
            "modalOverlay"
        );

    document.getElementById(
        "modalTitle"
    ).textContent=
        config.title||"";

    const messageEl=
        document.getElementById(
            "modalMessage"
        );

    messageEl.textContent=
        config.message||"";

    messageEl.style.display=
        config.message?"block":"none";

    const fieldsEl=
        document.getElementById(
            "modalFields"
        );

    fieldsEl.innerHTML="";

    (config.fields||[]).forEach(
        field=>{

            const wrap=
                document.createElement(
                    "div"
                );

            const label=
                document.createElement(
                    "label"
                );

            label.textContent=
                field.label;

            wrap.appendChild(label);

            const tag=
                field.type==="textarea"
                ?"textarea"
                :field.type==="select"
                ?"select"
                :"input";

            const input=
                document.createElement(
                    tag
                );

            input.className="input";

            input.id=
                "modalField_"+
                field.id;

            input.style.margin="0";

            if(field.type==="select"){

                input.innerHTML=
                    (field.options||[])
                    .map(opt=>

                        `<option value="${
                            opt.value
                        }">${
                            opt.label
                        }</option>`

                    )
                    .join("");

            }else{

                if(field.type&&
                    field.type!=="textarea")
                    input.type=field.type;

                if(field.placeholder)
                    input.placeholder=
                        field.placeholder;

            }

            if(field.value!==undefined)
                input.value=field.value;

            wrap.appendChild(input);

            fieldsEl.appendChild(wrap);

        }
    );

    const confirmBtn=
        document.getElementById(
            "modalConfirmBtn"
        );

    confirmBtn.textContent=
        config.confirmText||"SAVE";

    document.getElementById(
        "modalCancelBtn"
    ).style.display="";

    confirmBtn.onclick=()=>{

        const values={};

        let valid=true;

        (config.fields||[]).forEach(
            field=>{

                const el=
                    document.getElementById(
                        "modalField_"+
                        field.id
                    );

                const val=el.value;

                if(
                    field.required&&
                    !val.trim()
                ){
                    valid=false;
                }

                values[field.id]=val;

            }
        );

        if(!valid){

            toast(
                "Please fill in all fields"
            );

            return;

        }

        closeModal();

        config.onSubmit(values);

    };

    overlay.classList.add("show");

    setTimeout(()=>{

        const first=
            fieldsEl.querySelector(
                "input,textarea"
            );

        if(first)
            first.focus();

    },250);

}

