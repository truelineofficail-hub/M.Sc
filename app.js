function initScrollReveal(){

    if(
        window.matchMedia&&
        window.matchMedia(
            "(prefers-reduced-motion: reduce)"
        ).matches
    )
        return;

    if(!("IntersectionObserver" in window))
        return;

    const revealSelector=
        ".card, .stat, .chapter, .badge";

    const io=new IntersectionObserver(
        (entries,observer)=>{

            entries.forEach(entry=>{

                if(entry.isIntersecting){

                    entry.target
                    .classList.add(
                        "in-view"
                    );

                    observer.unobserve(
                        entry.target
                    );

                }

            });

        },
        {
            threshold:0.08,
            rootMargin:"0px 0px -30px 0px"
        }
    );

    function observeIn(root){

        if(!root||!root.nodeType)
            return;

        const nodes=[];

        if(
            root.matches&&
            root.matches(revealSelector)
        )
            nodes.push(root);

        if(root.querySelectorAll){

            root.querySelectorAll(
                revealSelector
            ).forEach(
                el=>nodes.push(el)
            );

        }

        nodes.forEach(el=>{

            if(
                el.classList.contains(
                    "reveal-init"
                )
            )
                return;

            el.classList.add(
                "reveal-init"
            );

            io.observe(el);

        });

    }

    observeIn(document.body);

    const appEl=
        document.querySelector(".app");

    if(!appEl)
        return;

    const mo=new MutationObserver(
        mutations=>{

            mutations.forEach(m=>{

                m.addedNodes.forEach(
                    node=>{

                        if(
                            node.nodeType===1
                        )
                            observeIn(node);

                    }
                );

            });

        }
    );

    mo.observe(appEl,{
        childList:true,
        subtree:true
    });

}

