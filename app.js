function updateTimer(){

    const min=
        Math.floor(
            timerSeconds/60
        )
        .toString()
        .padStart(2,"0");

    const sec=
        (timerSeconds%60)
        .toString()
        .padStart(2,"0");

    document.getElementById(
        "timerDisplay"
    ).textContent=
        min+":"+sec;

    const progress=
        1-
        timerSeconds/
        (currentTimerMinutes()*60);

    document.getElementById(
        "timerCircle"
    ).style.background=
        `conic-gradient(
            var(--orange)
            ${progress*360}deg,
            var(--track)
            ${progress*360}deg
        )`;

}

function runTimerInterval(){

    clearInterval(
        timerInterval
    );

    timerInterval=
        setInterval(()=>{

            if(!timerEndAt)
                return;

            const remaining=
                Math.round(
                    (timerEndAt-Date.now())/
                    1000
                );

            if(remaining<=0){

                timerSeconds=0;

                updateTimer();

                finishTimer();

                return;

            }

            timerSeconds=
                remaining;

            updateTimer();

            saveTimerState();

        },1000);

}

function startTimer(){

    if(timerRunning)
        return;

    if(timerSeconds<=0)
        timerSeconds=
            currentTimerMinutes()*60;

    timerRunning=true;

    timerEndAt=
        Date.now()+
        timerSeconds*1000;

    if(!timerStartDay)
        timerStartDay=
            todayDate();

    runTimerInterval();

    saveTimerState();

    toast(
        "Focus mode started 🔥"
    );

}

function pauseTimer(){

    clearInterval(
        timerInterval
    );

    if(timerEndAt){

        timerSeconds=
            Math.max(
                0,
                Math.round(
                    (timerEndAt-Date.now())/
                    1000
                )
            );

    }

    timerRunning=false;

    timerEndAt=null;

    updateTimer();

    saveTimerState();

    toast(
        "Timer paused"
    );

}

function resetTimer(){

    clearInterval(
        timerInterval
    );

    timerRunning=false;

    timerEndAt=null;

    timerStartDay=null;

    timerSeconds=
        currentTimerMinutes()*60;

    updateTimer();

    saveTimerState();

}

function finishTimer(){

    clearInterval(
        timerInterval
    );

    timerRunning=false;

    timerEndAt=null;

    const completedMinutes=
        currentTimerMinutes();

    const creditDay=
        timerStartDay||
        todayDate();

    addStudyMinutes(
        completedMinutes,
        creditDay
    );

    addMinutes(completedMinutes);

    updateDashboard();

    timerStartDay=null;

    timerSeconds=
        currentTimerMinutes()*60;

    updateTimer();

    saveTimerState();

    toast(
        completedMinutes+" minute session completed! 🔥"
    );

    if(
        "vibrate" in navigator
    ){

        navigator.vibrate(
            [200,100,200,100,400]
        );

    }

}

