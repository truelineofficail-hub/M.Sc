function renderHomeVacationPreview(){

    const container=
        document.getElementById(
            "homeVacationPreview"
        );

    if(!container)
        return;

    const now=new Date();

    const typeEmoji=
        type=>
            type==="vacation"
            ?"🏖️"
            :"📌";

    const viewAllLink=

        `<button
            class="btn full secondary"
            style="margin-top:12px"
            onclick="go('vacations')">
            VIEW ALL 2026 DATES
        </button>`;

    const current=
        VACATIONS.find(v=>{

            const start=
                new Date(
                    v.start+"T00:00:00"
                );

            const end=
                new Date(
                    v.end+"T23:59:59"
                );

            return now>=start&&now<=end;

        });

    if(current){

        const end=
            new Date(
                current.end+"T23:59:59"
            );

        const daysLeft=
            Math.ceil(
                (end-now)/
                (1000*60*60*24)
            );

        container.innerHTML=

            `<p style="
            font-size:13px;
            color:var(--text);
            margin-bottom:6px;
            font-weight:700">
            ${typeEmoji(current.type)} You're on ${escapeHTML(current.name)}
            — ${daysLeft} day${
                daysLeft===1?"":"s"
            } left
            </p>

            <p style="
            font-size:10px;
            color:var(--muted)">
            ${formatDateLong(
                new Date(current.start+"T00:00:00")
            )} – ${formatDateLong(
                new Date(current.end+"T00:00:00")
            )}
            </p>

            ${viewAllLink}`;

        return;

    }

    const upcoming=
        VACATIONS
        .map(v=>({
            ...v,
            startDate:new Date(
                v.start+"T00:00:00"
            )
        }))
        .filter(v=>v.startDate>now)
        .sort((a,b)=>
            a.startDate-b.startDate
        )[0];

    if(!upcoming){

        container.innerHTML=

            `<p style="
            font-size:13px;
            color:var(--muted);
            font-weight:700;
            margin-bottom:12px">
            No more 2026 dates scheduled.
            </p>

            ${viewAllLink}`;

        return;

    }

    const daysUntil=
        Math.ceil(
            (upcoming.startDate-now)/
            (1000*60*60*24)
        );

    container.innerHTML=

        `<p style="
        font-size:13px;
        color:var(--text);
        margin-bottom:6px;
        font-weight:700">
        ${typeEmoji(upcoming.type)} ${escapeHTML(upcoming.name)}
        in ${daysUntil} day${
            daysUntil===1?"":"s"
        }
        </p>

        <p style="
        font-size:10px;
        color:var(--muted)">
        ${formatDateLong(upcoming.startDate)} – ${formatDateLong(
            new Date(upcoming.end+"T00:00:00")
        )}
        </p>

        ${viewAllLink}`;

}

function renderVacationsPage(){

    const container=
        document.getElementById(
            "vacationsList"
        );

    if(!container)
        return;

    const now=new Date();

    container.innerHTML=

        VACATIONS.map(v=>{

            const start=
                new Date(
                    v.start+"T00:00:00"
                );

            const end=
                new Date(
                    v.end+"T23:59:59"
                );

            const isPast=
                end<now;

            const isCurrent=
                now>=start&&now<=end;

            const isMultiDay=
                v.start!==v.end;

            return `

                <div class="card" style="${
                    isPast
                    ?"opacity:.5"
                    :""
                }">

                    <div class="row">

                        <div class="row-main">

                            <strong>
                                ${v.type==="vacation"
                                ?"🏖️":"📌"} ${escapeHTML(v.name)}
                            </strong>

                            <p>
                                ${isMultiDay
                                ?formatDateLong(start)+" – "+formatDateLong(new Date(v.end+"T00:00:00"))
                                :formatDateLong(start)}
                            </p>

                        </div>

                        <span class="status ${
                            isCurrent
                            ?"progress"
                            :v.type==="vacation"
                            ?"done"
                            :""
                        }">
                            ${isCurrent
                            ?"ONGOING"
                            :v.type==="vacation"
                            ?"VACATION"
                            :"HOLIDAY"}
                        </span>

                    </div>

                </div>

            `;

        })
        .join("");

}

