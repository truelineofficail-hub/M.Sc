function formatTimeLeft(days){

    if(days<=0)
        return "0d";

    const years=
        Math.floor(days/365);

    const remAfterYears=
        days%365;

    const months=
        Math.floor(remAfterYears/30);

    if(years>0)
        return years+"y "+months+"mo";

    if(months>0)
        return months+"mo "+
            (remAfterYears%30)+"d";

    return days+"d";

}

