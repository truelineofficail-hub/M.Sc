function saveTarget(id,value){

    let number=
        Number(value);

    if(
        isNaN(number)||
        number<0
    )
        number=0;

    if(number>100)
        number=100;

    set(
        "target_"+id,
        number
    );

    updateAverageTarget();

    renderSubjects();

    toast(
        "Target updated 🎯"
    );

}

function updateAverageTarget(){

    let total=0;

    subjects.forEach(subject=>{

        total+=
            get(
                "target_"+subject.id,
                subject.target
            );

    });

    const average=
        Math.round(
            total/
            subjects.length
        );

    document.getElementById(
        "averageTarget"
    ).textContent=
        average+"%";

}

