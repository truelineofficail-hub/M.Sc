function renderWeeklyChart(){

    const container=
        document.getElementById(
            "weeklyChart"
        );

    if(!container)
        return;

    const data=
        getStudyData();

    const today=
        new Date();

    const days=[];

    for(let i=6;i>=0;i--){

        const date=
            new Date(today);

        date.setDate(
            today.getDate()-i
        );

        const year=
            date.getFullYear();

        const month=
            String(
                date.getMonth()+1
            ).padStart(2,"0");

        const day=
            String(
                date.getDate()
            ).padStart(2,"0");

        const key=
            `${year}-${month}-${day}`;

        days.push({

            key:key,

            date:date,

            minutes:data[key]||0

        });

    }

    const maxMinutes=
        Math.max(
            120,
            ...days.map(
                d=>d.minutes
            )
        );

    const total=
        days.reduce(
            (sum,d)=>
                sum+d.minutes,
            0
        );

    document.getElementById(
        "weeklyTotal"
    ).textContent=
        total+" min";

    container.innerHTML="";

    days.forEach(day=>{

        const wrapper=
            document.createElement(
                "div"
            );

        wrapper.className=
            "bar-wrap";

        const percentage=
            Math.min(
                100,
                day.minutes/
                maxMinutes*
                100
            );

        const isToday=
            day.key===todayDate();

        const dayName=
            day.date
            .toLocaleDateString(
                "en-US",
                {
                    weekday:"short"
                }
            )
            .charAt(0);

        wrapper.innerHTML=`

            <span class="bar-minutes">
                ${day.minutes}
            </span>

            <div class="bar-area">

                <div
                    class="bar ${
                        isToday
                        ?"today"
                        :""
                    }"
                    style="
                    height:${Math.max(
                        3,
                        percentage
                    )}%">
                </div>

            </div>

            <span class="bar-label">
                ${dayName}
            </span>

        `;

        container.appendChild(
            wrapper
        );

    });

}

