function get(key,fallback){

    try{

        const value=
            localStorage.getItem(key);

        return value===null
            ?fallback
            :JSON.parse(value);

    }catch{

        return fallback;

    }

}

function set(key,value){

    localStorage.setItem(
        key,
        JSON.stringify(value)
    );

}

function todayDate(){

    const now=new Date();

    const year=now.getFullYear();

    const month=
        String(
            now.getMonth()+1
        ).padStart(2,"0");

    const day=
        String(
            now.getDate()
        ).padStart(2,"0");

    return `${year}-${month}-${day}`;

}

