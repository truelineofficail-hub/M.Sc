let timerSeconds=
    currentTimerMinutes()*60;

let timerInterval=null;

let timerRunning=false;

let timerEndAt=null;

let timerStartDay=null;

function saveTimerState(){

    set("timerState",{
        running:timerRunning,
        endAt:timerEndAt,
        remaining:timerSeconds,
        startDay:timerStartDay,
        duration:selectedDuration,
        subject:
            document.getElementById(
                "timerSubject"
            )?document.getElementById(
                "timerSubject"
            ).value:subjects[0].id
    });

}

function restoreTimerState(){

    const state=
        get("timerState",null);

    if(!state)
        return;

    const select=
        document.getElementById(
            "timerSubject"
        );

    if(select&&state.subject)
        select.value=
            state.subject;

    if(state.duration)
        selectedDuration=
            state.duration;

    document
        .querySelectorAll(
            ".duration-btn"
        )
        .forEach(btn=>{

            btn.classList.toggle(
                "active",
                Number(btn.dataset.minutes)===
                selectedDuration
            );

        });

    timerStartDay=
        state.startDay||null;

    if(state.running&&state.endAt){

        const remaining=
            Math.round(
                (state.endAt-Date.now())/
                1000
            );

        if(remaining<=0){

            timerSeconds=0;

            updateTimer();

            finishTimer();

        }else{

            timerSeconds=
                remaining;

            timerEndAt=
                state.endAt;

            updateTimer();

            runTimerInterval();

        }

    }else{

        timerSeconds=
            typeof state.remaining
            ==="number"
            ?state.remaining
            :currentTimerMinutes()*60;

        updateTimer();

    }

}

