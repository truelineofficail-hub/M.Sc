function getSemesterDateRange(semester){

    if(semester===1){

        return {
            start:new Date(SEMESTER_1_START),
            end:new Date(SEMESTER_1_END)
        };

    }

    if(semester===2){

        return {
            start:new Date(SEMESTER_2_START),
            end:new Date(SEMESTER_2_END)
        };

    }

    const remainingStart=
        new Date(SEMESTER_3_START);

    const collegeEnd=
        new Date(COLLEGE_END);

    const remainingDays=
        (collegeEnd-remainingStart)/
        (1000*60*60*24);

    const perSemesterDays=
        remainingDays/2;

    const index=
        semester-3;

    const start=
        new Date(
            remainingStart.getTime()+
            index*perSemesterDays*
            (1000*60*60*24)
        );

    const end=
        new Date(
            remainingStart.getTime()+
            (index+1)*perSemesterDays*
            (1000*60*60*24)
        );

    return {start,end};

}

