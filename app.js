function exportData(){

    const data={};

    for(
        let i=0;
        i<localStorage.length;
        i++
    ){

        const key=
            localStorage.key(i);

        try{

            data[key]=
                JSON.parse(
                    localStorage.getItem(key)
                );

        }catch{

            data[key]=
                localStorage.getItem(key);

        }

    }

    const blob=
        new Blob(
            [
                JSON.stringify(
                    data,
                    null,
                    2
                )
            ],
            {
                type:
                    "application/json"
            }
        );

    const url=
        URL.createObjectURL(blob);

    const a=
        document.createElement(
            "a"
        );

    a.href=url;

    a.download=
        "microtrack-backup.json";

    a.click();

    URL.revokeObjectURL(url);

    toast(
        "Backup exported 💾"
    );

}

function importData(){

    const input=
        document.createElement(
            "input"
        );

    input.type="file";

    input.accept=".json";

    input.onchange=
        event=>{

            const file=
                event.target.files[0];

            if(!file)
                return;

            const reader=
                new FileReader();

            reader.onload=()=>{

                try{

                    const data=
                        JSON.parse(
                            reader.result
                        );

                    Object.entries(data)
                    .forEach(
                        ([key,value])=>{

                            localStorage.setItem(
                                key,
                                JSON.stringify(value)
                            );

                        }
                    );

                    location.reload();

                }catch{

                    toast(
                        "Invalid backup file"
                    );

                }

            };

            reader.readAsText(file);

        };

    input.click();

}

